-- ============================================================================
-- 카카오뱅크 저금통 데모 스키마
-- 원본: "1. ERD 추가자료 table_ddl.sql" (Oracle DDL)을 H2 Database
-- MODE=Oracle, 컬럼/타입/제약조건은 원본과 동일하게 유지
-- ============================================================================

DROP TABLE IF EXISTS IST_HIS;
DROP TABLE IF EXISTS PRD_RATE_HIST;
DROP TABLE IF EXISTS PIG_DTL;
DROP TABLE IF EXISTS PIG_ATO_EXC_HIST;
DROP TABLE IF EXISTS DLY_BLC_SNAPSHOT;
DROP TABLE IF EXISTS RST_HIS;
DROP TABLE IF EXISTS ACT_TRX;
DROP TABLE IF EXISTS PIG_MAS;
DROP TABLE IF EXISTS ACT_MAS;
DROP TABLE IF EXISTS CUS_MAS;

-- 1. CUS_MAS (고객)
CREATE TABLE CUS_MAS (
  CUS_NO      VARCHAR2(20) PRIMARY KEY,
  BIRTH_DATE  DATE         NOT NULL,
  VALD_YN     CHAR(1)      DEFAULT 'Y' NOT NULL
);

-- 2. ACT_MAS (계좌 — 입출금계좌/저금통계좌 공통)
CREATE TABLE ACT_MAS (
  ACNO         VARCHAR2(13)  PRIMARY KEY,
  CUS_NO       VARCHAR2(20)  NOT NULL,
  ACCD         VARCHAR2(10)  NOT NULL,        -- 상품구분 (DDA=입출금, PIG=저금통)
  BAL_AMT      NUMBER(15)    DEFAULT 0 NOT NULL,
  CNCL_YN      CHAR(1)       DEFAULT 'N' NOT NULL,
  RST_YN       CHAR(1)       DEFAULT 'N' NOT NULL,
  GRP_ACNO_YN  CHAR(1)       DEFAULT 'N' NOT NULL,
  OPN_DT       DATE          DEFAULT SYSDATE NOT NULL,
  CLS_DT       DATE          NULL,
  CNCL_CD      VARCHAR2(100) NULL,
  LAST_TRX_DT  DATE          DEFAULT SYSDATE NOT NULL,
  ISTOP_YN     CHAR(1)       DEFAULT 'N' NOT NULL,
  DORM_YN      CHAR(1)       DEFAULT 'N' NOT NULL,
  CONSTRAINT FK_ACT_MAS_CUSMAS FOREIGN KEY (CUS_NO) REFERENCES CUS_MAS (CUS_NO)
);

-- 3. PIG_MAS (저금통)
CREATE TABLE PIG_MAS (
  PIG_ACNO  VARCHAR2(13)  PRIMARY KEY,
  RT_ACNO   VARCHAR2(13)  NOT NULL,
  CUS_NO    VARCHAR2(20)  NOT NULL,
  BAL_AMT   NUMBER(15)    DEFAULT 0 NOT NULL,
  CNCL_YN   CHAR(1)       DEFAULT 'N' NOT NULL,
  ENR_DT    DATE          DEFAULT SYSDATE NOT NULL,
  CNCL_DT   DATE          NULL,
  CNCL_CD   VARCHAR2(20)  NULL,
  CONSTRAINT FK_PIG_MAS_ACTMAS_PIG FOREIGN KEY (PIG_ACNO) REFERENCES ACT_MAS (ACNO),
  CONSTRAINT FK_PIG_MAS_ACTMAS_RT  FOREIGN KEY (RT_ACNO)  REFERENCES ACT_MAS (ACNO),
  CONSTRAINT FK_PIG_MAS_CUSMAS     FOREIGN KEY (CUS_NO)   REFERENCES CUS_MAS (CUS_NO)
);


-- 4. ACT_TRX (계좌 거래내역 — 이중기장)
CREATE TABLE ACT_TRX (
  ACNO         VARCHAR2(13)  NOT NULL,
  TRX_SEQ_ID   NUMBER        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  TRX_DATE     DATE          NOT NULL,
  TRX_TYPE_CD  VARCHAR2(20)  NOT NULL,
  TRX_AMT      NUMBER(15)    NOT NULL,
  BF_BAL_AMT   NUMBER(15)    NOT NULL,
  AF_BAL_AMT   NUMBER(15)    NOT NULL,
  CNTP_ACNO    VARCHAR2(13)  NULL,
  TRX_GRP_ID   NUMBER        NULL,
  CONSTRAINT UK_ACT_TRX_ACNO_SEQ UNIQUE (ACNO, TRX_SEQ_ID),
  CONSTRAINT FK_ACT_TRX_ACTMAS FOREIGN KEY (ACNO) REFERENCES ACT_MAS (ACNO)
);
CREATE INDEX IX_ACT_TRX_CNTP ON ACT_TRX (CNTP_ACNO);

-- 5. RST_HIS (지급제한 이력)
CREATE TABLE RST_HIS (
  ACNO         VARCHAR2(13) NOT NULL,
  SEQ_ID       NUMBER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  RST_TYPE_CD  VARCHAR2(10) NOT NULL,
  RST_ST_CD    VARCHAR2(10) DEFAULT 'ACTV' NOT NULL,
  STRT_DATE    DATE         DEFAULT SYSDATE NOT NULL,
  END_DATE     DATE         NULL,
  CONSTRAINT UK_RST_HIS_ACNO_SEQ UNIQUE (ACNO, SEQ_ID),
  CONSTRAINT FK_RST_HIS_ACTMAS FOREIGN KEY (ACNO) REFERENCES ACT_MAS (ACNO)
);

-- 6. DLY_BLC_SNAPSHOT (일별 잔액 스냅샷)
CREATE TABLE DLY_BLC_SNAPSHOT (
  SEQ_ID     NUMBER        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  SNAP_DATE  DATE          NOT NULL,
  ACNO       VARCHAR2(13)  NOT NULL,
  CUS_NO     VARCHAR2(20)  NOT NULL,
  BAL_AMT    NUMBER(15)    NOT NULL,
  PROG_ID    VARCHAR2(30)  NOT NULL,
  CONSTRAINT UK_DLY_BLC_SNAPSHOT UNIQUE (ACNO, SNAP_DATE)
);

-- 7. PIG_ATO_EXC_HIST (저금통 자동저축 실행 이력)
CREATE TABLE PIG_ATO_EXC_HIST (
  PIG_ACNO       VARCHAR2(13) NOT NULL,
  SEQ_ID         NUMBER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  SVC_CD         VARCHAR2(10) NOT NULL,
  RT_ACNO        VARCHAR2(13) NOT NULL,
  EXC_DATE       DATE         NOT NULL,
  PREV_BAL_AMT   NUMBER(15)   NULL,
  CUR_BAL_AMT    NUMBER(15)   NULL,
  CALC_AMT       NUMBER(15)   DEFAULT 0 NOT NULL,
  EXC_AMT        NUMBER(15)   DEFAULT 0 NOT NULL,
  EXC_ST_CD      VARCHAR2(10) NOT NULL,            -- SUCC/SKIP/FAIL
  SKIP_RSN_CD    VARCHAR2(20) NULL,                -- BAL_LE_1000 / NO_CHANGE / LIMIT_EXCD / RST_ACTIVE
  FAIL_RSN_CD    VARCHAR2(20) NULL,
  TRX_SEQ_ID     NUMBER       NULL,
  CONSTRAINT UK_PIG_ATO_EXC_ACNO_SEQ UNIQUE (PIG_ACNO, SEQ_ID),
  CONSTRAINT CK_PIG_ATO_EXC_AMT CHECK (EXC_AMT >= 0 AND EXC_AMT <= CALC_AMT),
  CONSTRAINT FK_PIG_ATO_EXC_PIGMAS FOREIGN KEY (PIG_ACNO) REFERENCES PIG_MAS (PIG_ACNO),
  CONSTRAINT fk_ACT_TRX_PIG_ATO_EXC_HIST FOREIGN KEY (TRX_SEQ_ID) REFERENCES ACT_TRX (TRX_SEQ_ID)
);

-- 8. PIG_DTL (저금통 부가서비스 설정 이력)
CREATE TABLE PIG_DTL (
  PIG_ACNO   VARCHAR2(13)  NOT NULL,
  SVC_CD     VARCHAR2(10)  NOT NULL,
  SEQ_ID     NUMBER        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USE_YN     CHAR(1)       NOT NULL,
  APLY_DTTM  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  RG_GB_CD   VARCHAR2(10)  NULL,
  CONSTRAINT UK_PIG_DTL_ACNO_SVC_SEQ UNIQUE (PIG_ACNO, SVC_CD, SEQ_ID),
  CONSTRAINT fk_PIG_MAS_PIG_DTL FOREIGN KEY (PIG_ACNO) REFERENCES PIG_MAS (PIG_ACNO)
);

-- 9. PRD_RATE_HIST (상품별 금리 이력)
CREATE TABLE PRD_RATE_HIST (
  ACCD      VARCHAR2(10) NOT NULL,
  APLY_DT   DATE         NOT NULL,
  RATE_PCT  NUMBER(5,2)  NOT NULL,
  CONSTRAINT PK_PRD_RATE_HIST PRIMARY KEY (ACCD, APLY_DT)
);

-- 10. IST_HIS (이자지급 이력)
CREATE TABLE IST_HIS (
  ACNO        VARCHAR2(13) NOT NULL,
  SEQ_ID      NUMBER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  FR_DT       DATE         NOT NULL,
  TO_DT       DATE         NOT NULL,
  PAY_DT      DATE         NOT NULL,
  INT_AMT     NUMBER(15)   DEFAULT 0 NOT NULL,
  TRX_SEQ_ID  NUMBER       NULL,
  CONSTRAINT UK_IST_HIS_ACNO_SEQ UNIQUE (ACNO, SEQ_ID),
  CONSTRAINT UK_IST_HIS_ONCE UNIQUE (ACNO, PAY_DT),
  CONSTRAINT CK_IST_HIS_AMT CHECK (INT_AMT >= 0),
  CONSTRAINT FK_IST_HIS_ACTMAS FOREIGN KEY (ACNO) REFERENCES ACT_MAS (ACNO),
  CONSTRAINT FK_IST_HIS_TRX FOREIGN KEY (TRX_SEQ_ID) REFERENCES ACT_TRX (TRX_SEQ_ID)
);
